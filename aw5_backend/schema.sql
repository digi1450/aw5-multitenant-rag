CREATE TABLE IF NOT EXISTS projects (
    tenant_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_name text NOT NULL CHECK (length(trim(tenant_name)) BETWEEN 1 AND 70),
    guild_id bigint NOT NULL,
    discord_role_id bigint NOT NULL UNIQUE,
    dify_app_id uuid NOT NULL UNIQUE,
    dify_api_key_ciphertext bytea NOT NULL,
    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'active', 'suspended')),
    published_workflow_id uuid,
    last_sync_error text,
    synced_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS project_datasets (
    tenant_id bigint NOT NULL REFERENCES projects(tenant_id) ON DELETE CASCADE,
    dataset_id uuid NOT NULL,
    PRIMARY KEY (tenant_id, dataset_id)
);

CREATE TABLE IF NOT EXISTS tickets (
    thread_id bigint PRIMARY KEY,
    guild_id bigint NOT NULL,
    discord_user_id bigint NOT NULL,
    tenant_id bigint NOT NULL REFERENCES projects(tenant_id),
    dify_conversation_id text,
    closed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE tickets ADD COLUMN IF NOT EXISTS closed_at timestamptz;

CREATE INDEX IF NOT EXISTS tickets_owner_idx ON tickets(discord_user_id, tenant_id);
